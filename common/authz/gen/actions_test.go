const testModel = `model
  schema 1.1

type user

type cluster
  relations
    define owner: [user]
    define can_view: owner
    define can_delete: owner

type api_key
  relations
    define owner: [user]
    define can_edit: owner
    define can_use: owner
`

func parseTestModel(t *testing.T, dsl string) *Model {
	t.Helper()
	path := filepath.Join(t.TempDir(), "model.fga")
	require.NoError(t, os.WriteFile(path, []byte(dsl), 0o600))
	m, err := parseModel(path)
	require.NoError(t, err)
	return m
}

func names(c catalogue) []string {
	out := make([]string, 0, len(c.Actions))
	for _, a := range c.Actions {
		out = append(out, a.Name)
	}
	return out
}

func TestDeriveActionsTakesCanRelationsExceptExclusions(t *testing.T) {
	got := deriveActions(parseTestModel(t, testModel))

	require.Len(t, got, 3)
	assert.Equal(t, action{
		Name: "ACTION_CLUSTER_CAN_VIEW", GoName: "ClusterCanView", ObjectType: "cluster", Relation: "can_view",
	}, got[0])
	assert.Equal(t, "ACTION_CLUSTER_CAN_DELETE", got[1].Name)
	assert.Equal(t, action{
		Name: "ACTION_API_KEY_CAN_EDIT", GoName: "ApiKeyCanEdit", ObjectType: "api_key", Relation: "can_edit",
	}, got[2])
}

func TestAssignNumbersFromEmptyLockStartsAtOne(t *testing.T) {
	cat, lock := assignNumbers(deriveActions(parseTestModel(t, testModel)), map[string]int32{})

	assert.Equal(t, map[string]int32{
		"ACTION_CLUSTER_CAN_VIEW":   1,
		"ACTION_CLUSTER_CAN_DELETE": 2,
		"ACTION_API_KEY_CAN_EDIT":   3,
	}, lock)
	assert.Empty(t, cat.Reserved)
}

func TestAssignNumbersGivesNewRelationNextNumberAndKeepsExisting(t *testing.T) {
	actions := []action{{Name: "ACTION_A"}, {Name: "ACTION_NEW"}, {Name: "ACTION_B"}}
	cat, lock := assignNumbers(actions, map[string]int32{"ACTION_A": 7, "ACTION_B": 3})

	assert.Equal(t, map[string]int32{"ACTION_A": 7, "ACTION_B": 3, "ACTION_NEW": 8}, lock)
	assert.Equal(t, []string{"ACTION_B", "ACTION_A", "ACTION_NEW"}, names(cat), "ordered by number")
	assert.Empty(t, cat.Reserved)
}

func TestAssignNumbersReservesRemovedName(t *testing.T) {
	actions := []action{{Name: "ACTION_A"}, {Name: "ACTION_NEW"}}
	cat, lock := assignNumbers(actions, map[string]int32{"ACTION_A": 1, "ACTION_GONE": 5, "ACTION_OLD": 2})

	assert.Equal(t, map[string]int32{"ACTION_A": 1, "ACTION_GONE": 5, "ACTION_OLD": 2, "ACTION_NEW": 6}, lock,
		"a removed name stays in the lock and its number is never reused")
	assert.Equal(t, []int32{2, 5}, cat.Reserved)
}

func TestAssignNumbersReaddedNameGetsItsNumberBack(t *testing.T) {
	cat, _ := assignNumbers([]action{{Name: "ACTION_A"}}, map[string]int32{"ACTION_A": 4})

	assert.Equal(t, int32(4), cat.Actions[0].Number)
	assert.Empty(t, cat.Reserved)
}

func TestRenderProto(t *testing.T) {
	out := renderProto(catalogue{
		Actions:  []action{{Name: "ACTION_A", Number: 1}, {Name: "ACTION_C", Number: 3}},
		Reserved: []int32{2, 4},
	})

	assert.True(t, strings.HasPrefix(out, "// Code generated by go generate; DO NOT EDIT.\n"))
	assert.Contains(t, out, "enum Action {\n  reserved 2, 4;\n\n  ACTION_UNSPECIFIED = 0;\n  ACTION_A = 1;\n  ACTION_C = 3;\n}")

	noRemovals := renderProto(catalogue{Actions: []action{{Name: "ACTION_A", Number: 1}}})
	assert.Contains(t, noRemovals, "enum Action {\n  ACTION_UNSPECIFIED = 0;\n", "no reserved statement without removals")
}

func TestRenderGo(t *testing.T) {
	out, err := renderGo(catalogue{Actions: []action{
		{Name: "ACTION_API_KEY_CAN_EDIT", GoName: "ApiKeyCanEdit", ObjectType: "api_key", Relation: "can_edit", Number: 1},
	}})
	require.NoError(t, err)

	src := string(out)
	assert.True(t, strings.HasPrefix(src, "// Code generated by go generate; DO NOT EDIT.\n"))
	assert.Contains(t, src, `authzv1 "github.com/fundament-oss/fundament/authz-api/pkg/proto/gen/v1"`)
	assert.Contains(t, src, "ApiKeyCanEdit = authzv1.Action_ACTION_API_KEY_CAN_EDIT")
	assert.Contains(t, src, "return target{authz.ActionCanEdit, authz.ObjectTypeApiKey}")
	assert.Contains(t, src, "func All() []authzv1.Action")
}

func TestGenerateActionsIsIdempotentAndReservesRemovals(t *testing.T) {
	dir := t.TempDir()
	paths := actionPaths{
		lock:  filepath.Join(dir, "actions.lock.json"),
		proto: filepath.Join(dir, "actions.proto"),
		goSrc: filepath.Join(dir, "actions_gen.go"),
	}
	model := parseTestModel(t, testModel)

	require.NoError(t, generateActions(model, paths))
	lock, err := os.ReadFile(paths.lock)
	require.NoError(t, err)
	assert.JSONEq(t, `{"ACTION_CLUSTER_CAN_VIEW":1,"ACTION_CLUSTER_CAN_DELETE":2,"ACTION_API_KEY_CAN_EDIT":3}`, string(lock))
	proto, err := os.ReadFile(paths.proto)
	require.NoError(t, err)

	require.NoError(t, generateActions(model, paths))
	lockAgain, err := os.ReadFile(paths.lock)
	require.NoError(t, err)
	assert.Equal(t, string(lock), string(lockAgain))
	protoAgain, err := os.ReadFile(paths.proto)
	require.NoError(t, err)
	assert.Equal(t, string(proto), string(protoAgain))

	removed := parseTestModel(t, strings.Replace(testModel, "    define can_view: owner\n", "", 1))
	require.NoError(t, generateActions(removed, paths))
	proto, err = os.ReadFile(paths.proto)
	require.NoError(t, err)
	assert.Contains(t, string(proto), "reserved 1;")
	assert.NotContains(t, string(proto), "ACTION_CLUSTER_CAN_VIEW")
}

func TestGenerateActionsRejectsDuplicateLockNumbers(t *testing.T) {
	dir := t.TempDir()
	paths := actionPaths{
		lock:  filepath.Join(dir, "actions.lock.json"),
		proto: filepath.Join(dir, "actions.proto"),
		goSrc: filepath.Join(dir, "actions_gen.go"),
	}
	require.NoError(t, os.WriteFile(paths.lock, []byte(`{"ACTION_B":2,"ACTION_A":2,"ACTION_C":3}`), 0o600))

	err := generateActions(parseTestModel(t, testModel), paths)

	require.Error(t, err)
	assert.Contains(t, err.Error(), "ACTION_A")
	assert.Contains(t, err.Error(), "ACTION_B")
	assert.Contains(t, err.Error(), "number 2")
	assert.NoFileExists(t, paths.proto)
	assert.NoFileExists(t, paths.goSrc)
}

func TestGenerateActionsRefusesToRenumberWhenLockIsMissing(t *testing.T) {
	dir := t.TempDir()
	paths := actionPaths{
		lock:  filepath.Join(dir, "actions.lock.json"),
		proto: filepath.Join(dir, "actions.proto"),
		goSrc: filepath.Join(dir, "actions_gen.go"),
	}
	require.NoError(t, os.WriteFile(paths.goSrc, []byte("package actions\n"), 0o600))
	model := parseTestModel(t, testModel)

	err := generateActions(model, paths)

	require.Error(t, err)
	assert.Contains(t, err.Error(), paths.lock)
	assert.Contains(t, err.Error(), "-actions-init-lock")
	assert.NoFileExists(t, paths.lock)
	src, readErr := os.ReadFile(paths.goSrc)
	require.NoError(t, readErr)
	assert.Equal(t, "package actions\n", string(src), "nothing is written on failure")

	paths.initLock = true
	require.NoError(t, generateActions(model, paths))
	assert.FileExists(t, paths.lock)
}

func TestInitLockKeepsAnExistingLock(t *testing.T) {
	dir := t.TempDir()
	paths := actionPaths{
		lock:     filepath.Join(dir, "actions.lock.json"),
		proto:    filepath.Join(dir, "actions.proto"),
		goSrc:    filepath.Join(dir, "actions_gen.go"),
		initLock: true,
	}
	require.NoError(t, os.WriteFile(paths.lock, []byte(`{"ACTION_CLUSTER_CAN_VIEW":9}`), 0o600))

	require.NoError(t, generateActions(parseTestModel(t, testModel), paths))

	proto, err := os.ReadFile(paths.proto)
	require.NoError(t, err)
	assert.Contains(t, string(proto), "ACTION_CLUSTER_CAN_VIEW = 9;")
}

// The parser must see the same relations as OpenFGA's own on the real model.
func TestParserAgreesWithOpenFGA(t *testing.T) {
	dsl, err := os.ReadFile("../model.fga")
	require.NoError(t, err)
	parsed, err := transformer.TransformDSLToProto(string(dsl))
	require.NoError(t, err)

	var want []string
	for _, td := range parsed.GetTypeDefinitions() {
		for relation := range td.GetRelations() {
			if strings.HasPrefix(relation, "can_") && !excludedActions[td.GetType()+"."+relation] {
				want = append(want, td.GetType()+"."+relation)
			}
		}
	}

	got := make([]string, 0, len(want))
	for _, a := range deriveActions(parseTestModel(t, string(dsl))) {
		got = append(got, a.ObjectType+"."+a.Relation)
	}
	slices.Sort(want)
	slices.Sort(got)
	assert.Equal(t, want, got)
}
