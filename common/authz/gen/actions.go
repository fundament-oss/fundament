package main

import (
	"bytes"
	"cmp"
	"encoding/json"
	"errors"
	"fmt"
	"go/format"
	"io/fs"
	"maps"
	"os"
	"slices"
	"strconv"
	"strings"
	"text/template"
)

// excludedActions lists can_* relations that are not user-facing actions.
var excludedActions = map[string]bool{
	"api_key.can_use": true, // authn-api checks it when exchanging a key
}

type action struct {
	Name       string // proto enum value, ACTION_CLUSTER_CAN_DELETE
	GoName     string // Go constant, ClusterCanDelete
	ObjectType string
	Relation   string
	Number     int32
}

type catalogue struct {
	Actions  []action // ordered by number
	Reserved []int32  // numbers of names no longer in the model, ascending
}

type actionPaths struct {
	lock, proto, goSrc string
	initLock           bool // create a missing lock instead of failing
}

// deriveActions returns the actions in the model, in model order.
func deriveActions(m *Model) []action {
	var out []action
	for _, t := range m.Types {
		for _, r := range t.Relations {
			if !strings.HasPrefix(r, "can_") || excludedActions[t.Name+"."+r] {
				continue
			}
			out = append(out, action{
				Name:       "ACTION_" + strings.ToUpper(t.Name+"_"+r),
				GoName:     toPascalCase(t.Name) + toPascalCase(r),
				ObjectType: t.Name,
				Relation:   r,
			})
		}
	}
	return out
}

// assignNumbers numbers actions from the lock. A new name takes max+1. A name
// no longer in the model stays in the lock and its number becomes reserved.
func assignNumbers(actions []action, lock map[string]int32) (catalogue, map[string]int32) {
	updated := maps.Clone(lock)
	var highest int32
	for _, n := range lock {
		highest = max(highest, n)
	}

	var cat catalogue
	current := make(map[string]bool, len(actions))
	for _, a := range actions {
		current[a.Name] = true
		n, ok := updated[a.Name]
		if !ok {
			highest++
			n = highest
			updated[a.Name] = n
		}
		a.Number = n
		cat.Actions = append(cat.Actions, a)
	}
	slices.SortFunc(cat.Actions, func(x, y action) int { return cmp.Compare(x.Number, y.Number) })

	for name, n := range lock {
		if !current[name] {
			cat.Reserved = append(cat.Reserved, n)
		}
	}
	slices.Sort(cat.Reserved)
	return cat, updated
}

func renderProto(cat catalogue) string {
	var b strings.Builder
	b.WriteString(`// Code generated by go generate; DO NOT EDIT.
// Source: common/authz/model.fga and common/authz/actions/actions.lock.json.

edition = "2023";

package authz.v1;

option go_package = "github.com/fundament-oss/fundament/authz-api/pkg/proto/gen/v1;authzv1";

// A product action a caller may be allowed to take.
enum Action {
`)
	if len(cat.Reserved) > 0 {
		numbers := make([]string, 0, len(cat.Reserved))
		for _, n := range cat.Reserved {
			numbers = append(numbers, strconv.Itoa(int(n)))
		}
		fmt.Fprintf(&b, "  reserved %s;\n\n", strings.Join(numbers, ", "))
	}
	b.WriteString("  ACTION_UNSPECIFIED = 0;\n")
	for _, a := range cat.Actions {
		fmt.Fprintf(&b, "  %s = %d;\n", a.Name, a.Number)
	}
	b.WriteString("}\n")
	return b.String()
}

func renderGo(cat catalogue) ([]byte, error) {
	tmpl := template.Must(template.New("actions").Funcs(template.FuncMap{"pascal": toPascalCase}).Parse(actionsTemplate))
	var b bytes.Buffer
	if err := tmpl.Execute(&b, cat); err != nil {
		return nil, fmt.Errorf("execute template: %w", err)
	}
	src, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format source: %w", err)
	}
	return src, nil
}

// generateActions updates the lock and writes the proto and Go catalogue.
func generateActions(m *Model, paths actionPaths) error {
	lock, err := loadLock(paths)
	if err != nil {
		return err
	}
	cat, updated := assignNumbers(deriveActions(m), lock)

	src, err := renderGo(cat)
	if err != nil {
		return fmt.Errorf("render go: %w", err)
	}
	lockJSON, err := json.MarshalIndent(updated, "", "  ")
	if err != nil {
		return fmt.Errorf("encode lock: %w", err)
	}
	for path, content := range map[string][]byte{
		paths.lock:  append(lockJSON, '\n'),
		paths.proto: []byte(renderProto(cat)),
		paths.goSrc: src,
	} {
		if err := os.WriteFile(path, content, 0o644); err != nil { //nolint:gosec // generated source files; paths come from command-line flags
			return fmt.Errorf("write %s: %w", path, err)
		}
	}
	return nil
}

// loadLock reads the lock. A missing lock is an error once a catalogue exists,
// since numbering afresh would silently move every number.
func loadLock(paths actionPaths) (map[string]int32, error) {
	raw, err := os.ReadFile(paths.lock) //nolint:gosec // path comes from command-line flag
	if errors.Is(err, fs.ErrNotExist) {
		if _, statErr := os.Stat(paths.goSrc); statErr == nil && !paths.initLock {
			return nil, fmt.Errorf("lock %s is missing but %s exists: restore the lock from version control, "+
				"or pass -actions-init-lock to number every action afresh", paths.lock, paths.goSrc)
		}
		return map[string]int32{}, nil
	}
	if err != nil {
		return nil, fmt.Errorf("read lock: %w", err)
	}
	lock := map[string]int32{}
	if err := json.Unmarshal(raw, &lock); err != nil {
		return nil, fmt.Errorf("decode lock %s: %w", paths.lock, err)
	}

	byNumber := make(map[int32]string, len(lock))
	for _, name := range slices.Sorted(maps.Keys(lock)) {
		if other, taken := byNumber[lock[name]]; taken {
			return nil, fmt.Errorf("lock %s: %s and %s both have number %d: give the newer name a new number",
				paths.lock, other, name, lock[name])
		}
		byNumber[lock[name]] = name
	}
	return lock, nil
}

const actionsTemplate = `// Code generated by go generate; DO NOT EDIT.
// Source: common/authz/model.fga and common/authz/actions/actions.lock.json.

package actions

import (
	"fmt"

	"github.com/google/uuid"

	authzv1 "github.com/fundament-oss/fundament/authz-api/pkg/proto/gen/v1"
	"github.com/fundament-oss/fundament/common/authz"
)

const (
{{- range .Actions}}
	{{.GoName}} = authzv1.Action_{{.Name}}
{{- end}}
)

// All returns every defined action except the unspecified zero value.
func All() []authzv1.Action {
	return []authzv1.Action{
{{- range .Actions}}
		{{.GoName}},
{{- end}}
	}
}

// Relation returns the OpenFGA relation that grants a.
func Relation(a authzv1.Action) authz.Action {
	return authz.Action{Name: lookup(a).relation}
}

// Object returns the OpenFGA object a is checked against.
func Object(a authzv1.Action, id uuid.UUID) authz.Object {
	return authz.Object{Type: lookup(a).object, ID: id.String()}
}

type target struct {
	relation authz.ActionName
	object   authz.ObjectType
}

func lookup(a authzv1.Action) target {
	switch a {
{{- range .Actions}}
	case {{.GoName}}:
		return target{authz.Action{{pascal .Relation}}, authz.ObjectType{{pascal .ObjectType}}}
{{- end}}
	case authzv1.Action_ACTION_UNSPECIFIED:
		panic("actions: unspecified action")
	default:
		panic(fmt.Sprintf("actions: unmapped action %d", a))
	}
}
`
